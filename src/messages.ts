export type MessageKey = keyof typeof messages;
export type Translate = (key: MessageKey, params?: Record<string, string | number>) => string;
export function translator(language: Language): Translate {
  const index = { ru: 0, en: 1, pt: 2 }[language];
  return (key, params = {}) =>
    messages[key][index].replace(/\{(\w+)\}/g, (token, name) => String(params[name] ?? token));
}
export function categoryName(category: Category, t: Translate) {
  return category.mapId ? category.name : t(`cat_${category.id}` as MessageKey);
}
export function errorText(error: unknown, t: Translate) {
  const message = error instanceof Error ? error.message : String(error);
  const key = message.match(/ERR_[A-Z_]+/)?.[0];
  return key && key in messages ? t(key as MessageKey) : t('errorGeneric');
}
